# Lima pengujian bernilai True dan lima pengujian bernilai False.
print("True tests:")
print("python" == "python")
print(10 > 2)
print(5 <= 5)
print("A".lower() == "a")
print(3 < 5 and 8 > 2)

print("\nFalse tests:")
print("python" == "java")
print(2 > 10)
print(6 < 1)
print("A" == "a")
print(3 > 5 or 8 < 2)
